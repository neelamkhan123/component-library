// The same static registry `gen-examples.mjs` builds for component demos, but
// for `blocks/` — the multi-component feature compositions shown on /blocks.
// They are kept apart from `examples/` because they are addressed differently:
// an example belongs to one component page, a block is a page of its own.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const blocksDir = join(root, "blocks");
const outFile = join(root, "lib", "blocks.generated.ts");

mkdirSync(blocksDir, { recursive: true });

const files = readdirSync(blocksDir)
  .filter((file) => file.endsWith(".tsx"))
  .sort();

const identifier = (name) => "Block_" + name.replace(/[^a-zA-Z0-9]/g, "_");

const imports = [];
const entries = [];

for (const file of files) {
  const name = file.replace(/\.tsx$/, "");
  const raw = readFileSync(join(blocksDir, file), "utf8");

  // `"use client"` is a Next.js requirement, not something a reader copying
  // the block into their own app needs to see.
  const code = raw.replace(/^["']use client["'];?\s*\n+/, "").trimEnd();

  imports.push(`import ${identifier(name)} from "@/blocks/${name}";`);
  entries.push(`  ${JSON.stringify(name)}: { Component: ${identifier(name)}, code: ${JSON.stringify(code)} },`);
}

const output = `// AUTO-GENERATED by scripts/gen-blocks.mjs — do not edit.
import type { ComponentType } from "react";
${imports.join("\n")}

export type BlockSource = { Component: ComponentType; code: string };

export const blockSources: Record<string, BlockSource> = {
${entries.join("\n")}
};

export function getBlockSource(name: string): BlockSource | undefined {
  return blockSources[name];
}
`;

writeFileSync(outFile, output);
console.log(`gen-blocks: ${files.length} block(s) -> lib/blocks.generated.ts`);
