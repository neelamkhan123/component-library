// Builds a static registry of every file in `examples/` so a page can render
// a demo AND display its exact source. Generating explicit imports (rather
// than globbing at runtime) keeps the whole thing statically analysable, so
// the demos are bundled and pre-rendered like any other import.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const examplesDir = join(root, "examples");
const outFile = join(root, "lib", "examples.generated.ts");

mkdirSync(examplesDir, { recursive: true });

const files = readdirSync(examplesDir)
  .filter((file) => file.endsWith(".tsx"))
  .sort();

const identifier = (name) => "Ex_" + name.replace(/[^a-zA-Z0-9]/g, "_");

const imports = [];
const entries = [];

for (const file of files) {
  const name = file.replace(/\.tsx$/, "");
  const raw = readFileSync(join(examplesDir, file), "utf8");

  // `"use client"` is a Next.js requirement, not something a reader copying
  // the snippet into their own app needs to see, so it's trimmed from the
  // displayed source but left in the file that actually runs.
  const code = raw.replace(/^["']use client["'];?\s*\n+/, "").trimEnd();

  imports.push(`import ${identifier(name)} from "@/examples/${name}";`);
  entries.push(`  ${JSON.stringify(name)}: { Component: ${identifier(name)}, code: ${JSON.stringify(code)} },`);
}

const output = `// AUTO-GENERATED by scripts/gen-examples.mjs — do not edit.
import type { ComponentType } from "react";
${imports.join("\n")}

export type Example = { Component: ComponentType; code: string };

export const examples: Record<string, Example> = {
${entries.join("\n")}
};

export function getExample(name: string): Example | undefined {
  return examples[name];
}
`;

writeFileSync(outFile, output);
console.log(`gen-examples: ${files.length} example(s) -> lib/examples.generated.ts`);
